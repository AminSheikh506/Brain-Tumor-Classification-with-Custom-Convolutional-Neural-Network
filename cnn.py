"""## Predict images"""

def predict_image(model, img_path, class_names):
    # 1. Read model input shape
    _, img_h, img_w, channels = model.input_shape
    color_mode = 'grayscale' if channels == 1 else 'rgb'
    img = image.load_img(img_path,
                         color_mode=color_mode,
                         target_size=(img_h, img_w))
    img_array = image.img_to_array(img)

    if channels == 1 and img_array.shape[-1] == 3:
        # RGB -> grayscale
        img_array = tf.image.rgb_to_grayscale(img_array)
    elif channels == 3 and img_array.shape[-1] == 1:
        # grayscale -> RGB
        img_array = tf.image.grayscale_to_rgb(img_array)

    img_batch = np.expand_dims(img_array, axis=0)

    #Predict
    preds = model.predict(img_batch)
    probs = preds[0]

    #Get predicted class
    pred_index = np.argmax(probs)
    pred_class = class_names[pred_index]

    #Print probabilities
    print("\nClass probabilities:")
    for cls, p in zip(class_names, probs):
        print(f"  {cls:10} : {p*100:.2f}%")

    print("\nFinal Prediction:", pred_class)

    img_to_show = img_array.squeeze()

    if channels == 1:
       plt.imshow(img_to_show, cmap='gray')
    else:
       plt.imshow(img_to_show.astype("uint8"))
    plt.title(f"Prediction: {pred_class}")
    plt.axis("off")
    plt.show()

    return pred_class, probs
