# Commented out IPython magic to ensure Python compatibility.
import tensorflow as tf
import kagglehub

from tensorflow.keras import datasets, layers, models
import matplotlib.pyplot as plt
from sklearn.metrics import confusion_matrix, ConfusionMatrixDisplay
from sklearn.metrics import classification_report
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau
from tensorflow.keras.preprocessing import image


import numpy as np

# %matplotlib inline

"""## Importing Dataset From Kaggle




"""

# Download latest version
path = kagglehub.dataset_download("masoudnickparvar/brain-tumor-mri-dataset")

print("Path to dataset files:", path)

"""## Loading the Dataset"""

train_dir= path + '/Training'
test_dir= path + '/Testing'

train_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    labels='inferred',
    label_mode='int',
    color_mode='rgb',
    batch_size=32,
    image_size=(224, 224),
    shuffle=True,
    seed=42,
    validation_split=0.2,
    subset='training',
)

validation_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    labels='inferred',
    label_mode='int',
    color_mode='rgb',
    batch_size=32,
    image_size=(224, 224),
    shuffle=True,
    seed=42,
    validation_split=0.2,
    subset='validation',
)

test_ds = tf.keras.utils.image_dataset_from_directory(
    test_dir,
    labels='inferred',
    label_mode='int',
    color_mode='rgb',
    batch_size=32,
    image_size=(224, 224),
    shuffle=False,
    seed=42,
)

"""## Inspecting the Dataset
Checking the classes and a batch of images
"""

class_names = train_ds.class_names
print("Class names:", class_names)

for images, labels in train_ds.take(1):
    plt.figure(figsize=(10,10))
    for i in range(25):   # 25 images
        ax = plt.subplot(5, 5, i + 1)
        plt.imshow(images[i].numpy().astype("uint8"))
        plt.title(class_names[labels[i].numpy()])
        plt.axis("off")

"""## Preprocessing


1.   Normalizing
2.   Data Augmentation


"""

#Normalizing ,scaling to 0-1 from 0-255.
normalising_layer = tf.keras.layers.Rescaling(1./255)

#Data Augmentation, i.e, artificially creating training data from the same
#dataset by fliping the image,rotating the image and zooming the image randomly.

data_augment = tf.keras.Sequential([
    layers.RandomFlip('horizontal'),
    layers.RandomRotation(0.1,fill_mode="nearest"),
    layers.RandomTranslation(0.002, 0.002, fill_mode="nearest"),
    layers.RandomBrightness(factor=0.15),     # brightness_range=(0.85, 1.15) → factor = ±15%
    layers.RandomContrast(0.15),
    layers.RandomZoom(0.0,fill_mode='nearest'),
    layers.RandomTranslation(0.1, 0.1)
])

"""## Making the CNN Model"""

model = models.Sequential()
model.add(layers.Input(shape=(224,224,3))) #4 -5 layers need to add
#preprocessing layers
model.add(data_augment)
model.add(normalising_layer)
#cnn layers
model.add(layers.Conv2D(16, (4,4), activation='relu',padding='same'))
model.add(layers.MaxPooling2D((2,2)))


model.add(layers.Conv2D(32, (4,4), activation='relu',padding='same'))
model.add(layers.MaxPooling2D((2,2)))


model.add(layers.Conv2D(64, (4,4), activation='relu',padding='same'))
model.add(layers.MaxPooling2D((2,2)))

model.add(layers.Conv2D(128, (4,4), activation='relu',padding='same'))
model.add(layers.MaxPooling2D((2,2)))


model.add(layers.Conv2D(256, (4,4), activation='relu',padding='same'))
model.add(layers.MaxPooling2D((2,2)))


#flatten to a vector
model.add(layers.Flatten())
model.add(layers.Dense(512, activation='relu'))
model.add(layers.Dropout(0.5,seed=111))
model.add(layers.Dense(4, activation='softmax'))

#compile the model
optimizer = tf.keras.optimizers.Adam(learning_rate=0.001, beta_1=0.869, beta_2=0.995)
model.compile(optimizer=optimizer,
              loss=tf.keras.losses.SparseCategoricalCrossentropy(),
              metrics=['accuracy'])

"""## Model layer details"""

model.summary()

"""## Model Training"""

# Training
model_es = EarlyStopping(monitor='loss', min_delta=1e-9, patience=8, verbose=True)
model_rlr = ReduceLROnPlateau(monitor='val_loss', factor=0.3, patience=5, verbose=True)

history = model.fit(train_ds, epochs=40,
                    validation_data=validation_ds,
                    callbacks=[model_es,model_rlr])
#validation
plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend(loc='lower right')
plt.grid(True)
plt.show()

# Evaluate on test dataset
test_loss, test_acc = model.evaluate(test_ds)
print(f"Test Accuracy: {test_acc:0.5f}")
print(f"Test Loss: {test_loss:0.5f}")

